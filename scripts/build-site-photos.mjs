// Downloads the fixed-page photos listed in scripts/content/site-photos.json (or reads a
// source kept in the repo, given as a path relative to that list) and saves every
// width/format variant in public/images/site/{name}/{width}.{format}, using the same
// layout as uploaded photos (src/lib/content/photo-layout.json). Writes the size and alt
// text of each photo to src/lib/content/site-photos.json for the pages.
//
// Usage: npm run photos:site                  (all photos; re-run when the list changes)
//        npm run photos:site -- <name> ...     (only the named photos; others stay as they are)

import { mkdir, readFile, writeFile } from "node:fs/promises";

import sharp from "sharp";

import photoLayout from "../src/lib/content/photo-layout.json" with { type: "json" };

const PHOTO_LIST_FILE = new URL("./content/site-photos.json", import.meta.url);
const OUTPUT_DIRECTORY = new URL("../public/images/site/", import.meta.url);
const MANIFEST_FILE = new URL("../src/lib/content/site-photos.json", import.meta.url);
const QUALITY = { avif: 50, webp: 75 };

class SitePhotoError extends Error {
  constructor(message, context) {
    super(message);
    this.name = "SitePhotoError";
    this.context = context;
  }
}

async function fetchSourceImage(source) {
  if (!source.startsWith("https://")) return readFile(new URL(source, PHOTO_LIST_FILE));
  const response = await fetch(source);
  if (!response.ok) throw new SitePhotoError(`Download failed (${response.status})`, { source });
  return Buffer.from(await response.arrayBuffer());
}

async function saveVariants({ name, buffer }) {
  const folder = new URL(`${name}/`, OUTPUT_DIRECTORY);
  await mkdir(folder, { recursive: true });
  for (const width of photoLayout.widths) {
    for (const format of photoLayout.formats) {
      const body = await sharp(buffer).resize({ width, withoutEnlargement: true })[format]({ quality: QUALITY[format] }).toBuffer();
      await writeFile(new URL(`${width}.${format}`, folder), body);
    }
  }
}

// Crops a photo taller than the given width:height to its center band.
async function getCroppedImage({ source, aspect }) {
  const oriented = await sharp(source).rotate().toBuffer();
  if (!aspect) return oriented;
  const [ratioWidth, ratioHeight] = aspect.split(":").map(Number);
  const { width, height } = await sharp(oriented).metadata();
  const targetHeight = Math.round((width * ratioHeight) / ratioWidth);
  if (targetHeight >= height) return oriented;
  return sharp(oriented).extract({ left: 0, top: Math.round((height - targetHeight) / 2), width, height: targetHeight }).toBuffer();
}

async function buildPhoto({ name, source, alt, aspect }) {
  const buffer = await getCroppedImage({ source: await fetchSourceImage(source), aspect });
  const { width, height } = await sharp(buffer).metadata();
  await saveVariants({ name, buffer });
  console.log(`Saved ${name} (${width}×${height})`);
  return [name, { alt, width, height }];
}

function getSelectedPhotos(photos, names) {
  if (names.length === 0) return photos;
  const unknown = names.filter((name) => !photos.some((photo) => photo.name === name));
  if (unknown.length > 0) throw new SitePhotoError("Not in the photo list", { unknown });
  return photos.filter((photo) => names.includes(photo.name));
}

// Rebuilt photos replace their entries; every other photo keeps its saved size and alt
// text, and the list order is kept.
async function getPreviousEntries(names) {
  if (names.length === 0) return {};
  const { photos } = JSON.parse(await readFile(MANIFEST_FILE, "utf8"));
  return photos;
}

async function main() {
  const names = process.argv.slice(2);
  const { photos } = JSON.parse(await readFile(PHOTO_LIST_FILE, "utf8"));
  const previousEntries = await getPreviousEntries(names);
  const builtEntries = {};
  for (const photo of getSelectedPhotos(photos, names)) {
    const [name, entry] = await buildPhoto(photo);
    builtEntries[name] = entry;
  }
  const entries = photos.map(({ name }) => [name, builtEntries[name] ?? previousEntries[name]]);
  const missing = entries.filter(([, entry]) => !entry).map(([name]) => name);
  if (missing.length > 0) throw new SitePhotoError("Never built; run without names first", { missing });
  const manifest = { $comment: "Generated by scripts/build-site-photos.mjs; do not edit by hand.", photos: Object.fromEntries(entries) };
  await writeFile(MANIFEST_FILE, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`Site photos finished: ${Object.keys(builtEntries).length} of ${photos.length} photos rebuilt.`);
}

main().catch((error) => {
  console.error(`Site photos failed: ${error.message}`, error.context ?? "");
  process.exitCode = 1;
});
